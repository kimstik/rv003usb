#!/usr/bin/env python3
"""fronts.py — Pareto front computation per chip profile on (quality, MHz),
with flash/RAM as hard constraints at real chip limits.

Reads results/pareto.csv (built by collect.py). Writes:
  results/fronts.json      — feasibility + fronts + price-of-choice, machine form
  results/fronts.md        — the same as markdown tables (embedded in REPORT.md)

Two jurisdictions are kept separate (their LSDs live on different floors and
are NOT comparable):
  * engine family : quality = lsd_engine_db (real hts1a vs sinusoid reference,
                    floor ~3.5 dB), cost = MHz on the chip's regime.
  * system family : quality = lsd_sys_db (q1300 vs codec2 phase0 reference,
                    floor ~7.6 dB) with estoi_orig/crest as annotations.

Chip regimes: P1/P3 chips have a 1-cycle (or hw) multiplier -> mhz_p1 column;
P2 (CH32V003, RV32EC no mul) -> mhz_p2 column (asm-audited where available).

Feasibility: engine/system RAM+flash must fit the chip alongside the REST of
the codec (bitstream tables, frame buffers, encoder). We charge a fixed
overhead reserve: OVERHEAD_RAM=512 B, OVERHEAD_FLASH=6144 B (decoder tables +
code, conservative round figure — flagged as an assumption, not a measurement)
and require cfg_ram + reserve <= chip RAM, cfg_flash + reserve <= chip flash,
MHz <= 50% of the chip clock (half-duplex: the encoder needs the other half).
Rows with unknown RAM/flash are treated as feasible-unknown (marked '?') and
still shown, since for rungs only the L0 base was sized.
"""
import csv
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OVERHEAD_RAM = 512
OVERHEAD_FLASH = 6144
MHZ_BUDGET_FRAC = 0.50

CHIPS = {
    # name: (profile, clock MHz, RAM B, flash B, mhz column)
    "PY32F003x8": ("P1", 24, 8 * 1024, 64 * 1024, "mhz_p1"),
    "CH32V003": ("P2", 48, 2 * 1024, 16 * 1024, "mhz_p2"),
    "CH32V006": ("P1", 48, 8 * 1024, 62 * 1024, "mhz_p1"),
    "CH570": ("P3", 100, 12 * 1024, 240 * 1024, "mhz_p1"),
    "CH32V203": ("P3", 144, 20 * 1024, 64 * 1024, "mhz_p1"),
}


def num(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return None


rows = list(csv.DictReader(open(HERE / "results/pareto.csv")))

FAMS = {
    "engine": ("lsd_engine_db", "engine jurisdiction: LSD hts1a vs sinusoid ref"),
    "system": ("lsd_sys_db", "system jurisdiction: LSD q1300 vs codec2 phase0 ref"),
}


def family_rows(fam):
    if fam == "engine":
        return [r for r in rows if r["family"] == "engine"]
    return [r for r in rows if r["family"] in ("system-rung", "variant")]


def front_eligible(r):
    """Configs killed by the source experiments (for OFF-axis reasons a single
    LSD axis cannot see: grid worst cases, spurs, aliasing) or unstable ones do
    not get a seat on the front; they stay in the dataset and plots."""
    if r["verdict"] == "killed" or r["stability"].startswith("unstable"):
        return False
    # L-dependent engines are costed at worst case (L=80): a decoder cannot
    # choose its speaker's pitch. Per-L rows remain in the dataset for the
    # cost-scaling picture; only worst-case rows may sit on the front.
    if " L=" in r["config"] and not r["config"].endswith("L=80"):
        return False
    return True


def feasible(r, chip):
    _, clock, ram, flash, mcol = CHIPS[chip]
    mhz = num(r[mcol])
    if mhz is None:
        return None, "no cost measured for this regime"
    if mhz > clock * MHZ_BUDGET_FRAC:
        return False, f"{mhz:.2f} MHz > {MHZ_BUDGET_FRAC:.0%} of {clock} MHz"
    rb, fb = num(r["ram_b"]), num(r["flash_b"])
    why = []
    if rb is not None and rb + OVERHEAD_RAM > ram:
        why.append(f"RAM {rb:.0f}+{OVERHEAD_RAM} > {ram}")
    if fb is not None and fb + OVERHEAD_FLASH > flash:
        why.append(f"flash {fb:.0f}+{OVERHEAD_FLASH} > {flash}")
    if why:
        return False, "; ".join(why)
    if rb is None or fb is None:
        return True, "RAM/flash not sized (gap) — feasible on MHz only"
    return True, ""


def pareto_front(cands, qcol, mcol):
    """min quality (LSD dB) and min MHz. Returns list sorted by MHz."""
    front = []
    for r in cands:
        q, m = num(r[qcol]), num(r[mcol])
        dominated = False
        for s in cands:
            q2, m2 = num(s[qcol]), num(s[mcol])
            if (q2 <= q and m2 <= m) and (q2 < q or m2 < m):
                dominated = True
                break
        if not dominated:
            front.append(r)
    return sorted(front, key=lambda r: num(r[mcol]))


out = {"assumptions": {
    "overhead_ram_b": OVERHEAD_RAM, "overhead_flash_b": OVERHEAD_FLASH,
    "mhz_budget_frac": MHZ_BUDGET_FRAC,
    "note": "overhead reserve is an assumption (rest-of-codec), not a measurement",
}, "chips": {}}
md = ["<!-- generated by fronts.py — do not edit by hand -->", ""]

for chip, (profile, clock, ram, flash, mcol) in CHIPS.items():
    chip_out = {"profile": profile, "clock_mhz": clock, "ram_b": ram,
                "flash_b": flash, "mhz_column": mcol, "families": {}}
    md.append(f"## {chip} ({profile}, {clock} MHz, {ram//1024}K RAM / "
              f"{flash//1024}K flash)")
    for fam, (qcol, jnote) in FAMS.items():
        frs = family_rows(fam)
        feas, infeas, unmeasured = [], [], []
        for r in frs:
            ok, why = feasible(r, chip)
            if ok is None:
                unmeasured.append((r, why))
            elif ok:
                feas.append((r, why))
            else:
                infeas.append((r, why))
        cands = [r for r, _ in feas
                 if num(r[qcol]) is not None and front_eligible(r)]
        front = pareto_front(cands, qcol, mcol)
        # secondary front for the system family: crest-delta axis (temporal
        # texture / anti-buzz) — the axis where L2 pays, which LSD hides.
        front2 = []
        if fam == "system":
            c2 = [r for r in cands if num(r["crest_delta_db"]) is not None]

            def dom(a, b):
                qa, qb = abs(num(a["crest_delta_db"])), abs(num(b["crest_delta_db"]))
                ma, mb = num(a[mcol]), num(b[mcol])
                return (qb <= qa and mb <= ma) and (qb < qa or mb < ma)
            front2 = sorted([a for a in c2 if not any(dom(a, b) for b in c2)],
                            key=lambda r: num(r[mcol]))
        # price of choice between adjacent front points
        price = []
        for a, b in zip(front, front[1:]):
            dq = num(a[qcol]) - num(b[qcol])       # dB LSD you gain (positive)
            dm = num(b[mcol]) - num(a[mcol])
            fa, fb = num(a["flash_b"]), num(b["flash_b"])
            df = (fb - fa) if (fa is not None and fb is not None) else None
            price.append({
                "from": a["config"], "to": b["config"],
                "dLSD_dB": round(-dq, 3) if False else round(dq, 3),
                "dMHz": round(dm, 3),
                "dB_per_MHz": round(dq / dm, 3) if dm else None,
                "dFlash_B": df,
                "dB_per_KB_flash": round(dq / (df / 1024), 3) if df else None,
            })
        chip_out["families"][fam] = {
            "jurisdiction": jnote,
            "feasible": [r["config"] for r, _ in feas],
            "feasible_unsized": [r["config"] for r, w in feas if "not sized" in w],
            "infeasible": {r["config"]: w for r, w in infeas},
            "front": [{
                "config": r["config"], "tier": r["tier"],
                "lsd_db": num(r[qcol]), "mhz": num(r[mcol]),
                "core_pct": round(100 * num(r[mcol]) / clock, 1),
                "ram_b": r["ram_b"], "flash_b": r["flash_b"],
                "estoi_orig": r["estoi_orig"], "nisqa_mos": r["nisqa_mos"],
                "stability": r["stability"],
            } for r in front],
            "front_crest": [{
                "config": r["config"], "tier": r["tier"],
                "crest_delta_db": num(r["crest_delta_db"]),
                "lsd_db": num(r[qcol]), "mhz": num(r[mcol]),
            } for r in front2],
            "price_of_choice": price,
        }
        # markdown
        md.append(f"\n### {fam} front — {jnote}\n")
        md.append("| config | tier | LSD dB | MHz | % core | RAM B | flash B | stability |")
        md.append("|---|---|---|---|---|---|---|---|")
        for r in front:
            md.append(f"| {r['config']} | {r['tier'] or '—'} | {r[qcol]} | "
                      f"{r[mcol]} | {100*num(r[mcol])/clock:.1f}% | "
                      f"{r['ram_b'] or '?'} | {r['flash_b'] or '?'} | "
                      f"{r['stability'].split('(')[0].strip() or '—'} |")
        if price:
            md.append("\nPrice of choice (adjacent front points):\n")
            md.append("| step | ΔLSD dB | ΔMHz | dB/MHz | Δflash B | dB/KB |")
            md.append("|---|---|---|---|---|---|")
            for p in price:
                md.append(f"| {p['from']} → {p['to']} | {p['dLSD_dB']:+.2f} | "
                          f"{p['dMHz']:+.2f} | {p['dB_per_MHz'] if p['dB_per_MHz'] is not None else '—'} | "
                          f"{int(p['dFlash_B']) if p['dFlash_B'] is not None else '—'} | "
                          f"{p['dB_per_KB_flash'] if p['dB_per_KB_flash'] is not None else '—'} |")
        if front2:
            md.append("\nSecondary system front on |crest Δ| (temporal "
                      "texture / anti-buzz — the axis where L2 pays and "
                      "which LSD hides):\n")
            md.append("| config | tier | crest Δ dB | LSD dB | MHz |")
            md.append("|---|---|---|---|---|")
            for r in front2:
                md.append(f"| {r['config']} | {r['tier'] or '—'} | "
                          f"{r['crest_delta_db']} | {r[qcol]} | {r[mcol]} |")
        if infeas:
            md.append("\nInfeasible: " + "; ".join(
                f"**{r['config']}** ({w})" for r, w in infeas))
        md.append("")
    out["chips"][chip] = chip_out

# ------------------------------------------------- per-chip feasibility matrix
KEY_CONFIGS = [
    "tube-L0", "tube-L1", "tube-L2-2500", "tube-L4-0.50",
    "tube-rec-P1 (L0+L1+L2.5k+L4)", "tube-rec-P2 (L0+L2.5k+L4)",
    "impulse-iir", "impulse-iir-csd-sos (jit)", "impulse-iir-csd-sos (interp)",
    "lsp-allpass-csd3", "kl-lattice-csd3",
    "osc-bank L=80", "cycle-replay-2x L=80", "cr-rt-lin L=80",
    "meander-tri L=80", "parallel-sos-csd3",
]
md.append("## Per-chip feasibility matrix (key configs)\n")
md.append("Cell: `core-%` if it fits (MHz ≤ 50% clock, RAM/flash + reserve fit); "
          "`?` = fits on MHz but RAM/flash not sized (coverage gap); "
          "`✗` = infeasible (reason).\n")
md.append("| config | " + " | ".join(CHIPS) + " |")
md.append("|---|" + "---|" * len(CHIPS))
cfg_by_name = {r["config"]: r for r in rows}
matrix = {}
for name in KEY_CONFIGS:
    r = cfg_by_name.get(name)
    if not r:
        continue
    cells = []
    for chip, (_, clock, *_rest) in CHIPS.items():
        ok, why = feasible(r, chip)
        mhz = num(r[CHIPS[chip][4]])
        if ok is None:
            cells.append("—")
        elif not ok:
            cells.append(f"✗ ({why})")
        elif "not sized" in why:
            cells.append(f"{100*mhz/clock:.1f}% ?")
        else:
            cells.append(f"{100*mhz/clock:.1f}%")
        matrix.setdefault(name, {})[chip] = cells[-1]
    md.append(f"| {name} | " + " | ".join(cells) + " |")
md.append("")
out["feasibility_matrix"] = matrix

(HERE / "results/fronts.json").write_text(json.dumps(out, indent=1))
(HERE / "results/fronts.md").write_text("\n".join(md))
print("wrote results/fronts.json + results/fronts.md")
for chip in CHIPS:
    for fam in FAMS:
        f = out["chips"][chip]["families"][fam]["front"]
        print(f"{chip:11s} {fam:7s} front: " +
              " -> ".join(f"{p['config']} ({p['lsd_db']}dB @{p['mhz']}MHz)" for p in f))
